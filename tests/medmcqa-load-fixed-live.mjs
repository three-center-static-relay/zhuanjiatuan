import assert from "node:assert/strict";
import {createHash} from "node:crypto";
const RAW="https://raw.githubusercontent.com/aistairc/medLLM_QA_benchmark/main/data/en/MedMCQA/medmcqa.jsonl";
const d=await fetch(RAW,{headers:{accept:"text/plain"}});const bytes=Buffer.from(await d.arrayBuffer());
assert.equal(d.status,200,`RAW_HTTP_${d.status}`);
assert.ok(bytes.length>1_000_000,"RAW_TOO_SMALL");
const h=createHash("sha1");h.update(Buffer.from(`blob ${bytes.length}\0`));h.update(bytes);const sha=h.digest("hex");
assert.equal(sha,"91205dc035b83fd173464aa46e0008302a0b3771",`BLOB_SHA_${sha}`);
const text=bytes.toString("utf8"),rows=text.split(/\r?\n/).filter(Boolean);
assert.ok(rows.length>=2000&&rows.length<=10000,`ROWS_${rows.length}`);
const first=JSON.parse(rows[0]);assert.equal(Array.isArray(first?.choices),true);assert.equal(first.choices.length,4);assert.match(String(first?.answer?.[0]||""),/^[abcd]$/i);
console.log(JSON.stringify({ok:true,suite:"medmcqa-raw-sha",paid_call:false,bytes:bytes.length,rows:rows.length,blob_sha:sha}));
