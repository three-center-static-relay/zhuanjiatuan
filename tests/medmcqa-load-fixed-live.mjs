import assert from "node:assert/strict";
const RAW="https://raw.githubusercontent.com/aistairc/medLLM_QA_benchmark/main/data/en/MedMCQA/medmcqa.jsonl";
const BASE="https://expert-worker.a15280020511.workers.dev/v1/diag/medmcqa-2f9c7e11-20260817";
const d=await fetch(RAW,{headers:{accept:"text/plain"}});const raw=await d.text();
assert.equal(d.status,200,`RAW_HTTP_${d.status}`);
const r=await fetch(`${BASE}/probe-upload`,{method:"POST",headers:{"content-type":"text/plain; charset=utf-8"},body:raw});const b=await r.json().catch(()=>null);
assert.equal(r.status,200,`UPLOAD_HTTP_${r.status}:${JSON.stringify(b)}`);
assert.equal(b?.ok,true,JSON.stringify(b));
assert.equal(b?.upload_verified,true,JSON.stringify(b));
assert.equal(b?.blob_sha,"91205dc035b83fd173464aa46e0008302a0b3771",JSON.stringify(b));
assert.equal(b?.total,4183,`UNEXPECTED_TOTAL:${JSON.stringify(b)}`);
assert.equal(b?.chunk_size,23,JSON.stringify(b));
console.log(JSON.stringify({ok:true,suite:"medmcqa-upload-probe-live",paid_call:false,total:b.total,bytes:b.bytes,blob_sha:b.blob_sha,first_id:b.first_id,last_id:b.last_id}));
