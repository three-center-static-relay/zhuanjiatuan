import assert from "node:assert/strict";
import app from "../src/legacy-removed-entry.js";
const run=await app.fetch(new Request("https://expert.internal/v1/run",{method:"POST"}));
assert.equal(run.status,410);
const runBody=await run.json();
assert.equal(runBody.error,"LEGACY_EXPERT_PANEL_REMOVED");
assert.equal(runBody.legacy_expert_panel_removed,true);
assert.equal(runBody.fail_closed,true);
const health=await app.fetch(new Request("https://expert.internal/health"));
assert.equal(health.status,200);
const healthBody=await health.json();
assert.equal(healthBody.accepting_tasks,false);
assert.equal(healthBody.legacy_expert_panel_removed,true);
const caps=await app.fetch(new Request("https://expert.internal/v1/capabilities"));
const capsBody=await caps.json();
assert.equal(capsBody.capabilities.legacy_expert_panel,false);
assert.equal(capsBody.capabilities.accepting_tasks,false);
console.log(JSON.stringify({ok:true,suite:"legacy-expert-panel-removed",legacy_run_blocked:true,fail_closed:true,replacement:"expert-v4.1-pending"}));
