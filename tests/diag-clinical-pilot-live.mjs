import assert from "node:assert/strict";
const u="https://expert-worker.a15280020511.workers.dev/v1/clinical-benchmark/8c43af0e-20260817/stemi";
const r=await fetch(u,{headers:{accept:"application/json"}});const b=await r.json().catch(()=>null);
assert.equal(r.status,200,`HTTP_${r.status}:${JSON.stringify(b)}`);
assert.equal(b?.ok,true,`NOT_OK:${JSON.stringify(b)}`);
assert.equal(b?.model_count,2);
assert.equal(b?.company_diverse,true);
assert.ok(String(b?.judge_output||"").trim().length>80);
assert.equal(b?.score,100,`SCORE_${b?.score}:${JSON.stringify(b?.checks)}`);
assert.ok(Array.isArray(b?.checks)&&b.checks.every(x=>x.ok===true),JSON.stringify(b?.checks));
console.log(JSON.stringify({ok:true,suite:"clinical-benchmark-stemi",score:b.score,checks:b.checks,models:b.models,judge_model:b.judge_model,cached:b.cached}));
